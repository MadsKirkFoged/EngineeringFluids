    // ===== Low region (<= 403): 2°C segments =====
    private const float SegW_Lo = 2.0f;
    private const float InvSegW_Lo = 0.5f;    // 1/2
    private const float Half_Lo = 1.0f;    // SegW/2
    private const float TAnchor_Lo = 195.000000000f;
    private const int NSeg_Lo = 104;

    // ===== High region (> 403): 0.01°C segments (aligned to the 0.005°C grid) =====
    private const float SegW_Hi = 0.01f;
    private const float InvSegW_Hi = 100.0f;  // 1/0.01
    private const float Half_Hi = 0.005f;  // SegW/2
    private const float TAnchor_Hi = 403.000000000f;
    private const int NSeg_Hi = 256;

    /// <summary>
    /// Returns the molar density for a given temperature.
    /// </summary>
    public static Molarity Density(Temperature t)
        => Molarity.FromMolesPerCubicMeter(Density((float)t.Kelvin));

    /// <summary>
    /// Returns molar density (mol/m3) for a given temperature (K).
    /// </summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining | MethodImplOptions.AggressiveOptimization)]
    internal static float Density(float t)
    {
        // Clamp to domain
        if (t < Tmin)
            t = Tmin;
        else if (t > Tmax)
            t = Tmax;

        if (t <= Tsplit)
        {
            int k = (int)((t - TAnchor_Lo) * InvSegW_Lo);
            if ((uint)k >= (uint)NSeg_Lo)
                k = (k < 0) ? 0 : (NSeg_Lo - 1);

            float mid = TAnchor_Lo + (k + 0.5f) * SegW_Lo;
            float u = (t - mid) / Half_Lo;

            int o = k * 3;
            float c0 = CoeffLow[o + 0];
            float c1 = CoeffLow[o + 1];
            float c2 = CoeffLow[o + 2];

            float y = MathF.FusedMultiplyAdd(c2, u, c1);
            return MathF.FusedMultiplyAdd(y, u, c0);
        }
        else
        {
            int k = (int)((t - TAnchor_Hi) * InvSegW_Hi);
            if ((uint)k >= (uint)NSeg_Hi)
                k = (k < 0) ? 0 : (NSeg_Hi - 1);

            float mid = TAnchor_Hi + (k + 0.5f) * SegW_Hi;
            float u = (t - mid) / Half_Hi; // Half_Hi=0.005 -> u = 200*(t-mid)

            int o = k * 3;
            float c0 = CoeffHigh[o + 0];
            float c1 = CoeffHigh[o + 1];
            float c2 = CoeffHigh[o + 2];

            float y = MathF.FusedMultiplyAdd(c2, u, c1);
            return MathF.FusedMultiplyAdd(y, u, c0);
        }
    }

