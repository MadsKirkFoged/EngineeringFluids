    private const float SegW_Lo = 2.0f;
    private const float InvSegW_Lo = 0.5f;    // 1/2
    private const float Half_Lo = 1.0f;    // SegW/2
    private const float TAnchor_Lo = 195.000000000f;
    private const int NSeg_Lo = 104;

    // ===== High region (> 403): 0.01°C segments (aligned to the 0.005°C grid) =====
    private const float SegW_Hi = 0.01f;
    private const float InvSegW_Hi = 100.0f;  // 1/0.01
    private const float Half_Hi = 0.005f;  // SegW/2
    private const float TAnchor_Hi = 403.000000000f;
